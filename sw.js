const CACHE_NAME = 'tbf-shell-v1';
const APP_SHELL_ASSETS = [
  '/',
  '/index.html',
  '/js/qrcode.js',
  '/js/qrcode_UTF8.js',
  '/js/app.js',
  '/images/market_tents_aisle.jpg',
  '/images/african_market_stalls.jpg',
  '/images/sabasaba_event.jpg'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL_ASSETS).catch(() => {}))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Network-first for API data & HTML/JS updates, falling back to cache when offline/slow
  if (url.pathname.startsWith('/api/data') || url.pathname === '/' || url.pathname === '/index.html' || url.pathname.startsWith('/js/')) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, copy)).catch(() => {});
          }
          return res;
        })
        .catch(() => caches.match(req).then((hit) => hit || caches.match('/index.html')))
    );
    return;
  }

  // Cache-first for local static images so weak connections don't stall visuals
  if (url.pathname.startsWith('/images/')) {
    event.respondWith(
      caches.match(req).then((cached) => {
        if (cached) return cached;
        return fetch(req).then((res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, copy)).catch(() => {});
          }
          return res;
        });
      })
    );
  }
});
